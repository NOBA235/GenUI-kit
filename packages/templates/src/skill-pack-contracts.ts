export function buildInvariantsTestTs(ctx: SkillPackContext): string {
  const initialState = ctx.initialObservableState;
  return `${GENERATED_HEADER(ctx.document.brief.title)}
//
// Behavioral contract tests over AppDriver.
//   GENUI_DRIVER_TARGET=reference -> contracts/reference-driver.ts (bundled model, passes)
//   anything else (default)       -> contracts/production-driver.ts (your app)
// GENUI_CONTRACT_RUNS overrides the number of fast-check runs (default ${ctx.fuzzSettings.numRuns}).
import { describe, expect, it } from "vitest";
import * as fc from "fast-check";
import type { AppDriver, InteractionEvent, OutcomeStatus } from "./app-driver";
import { createProductionDriver } from "./production-driver";
import { createReferenceDriver } from "./reference-driver";

const TARGET = process.env.GENUI_DRIVER_TARGET === "reference" ? "reference" : "production";

function createDriver(): AppDriver {
  return TARGET === "reference" ? createReferenceDriver() : createProductionDriver();
}

interface VerifiedTrace {
  readonly outcome: OutcomeStatus;
  readonly events: readonly InteractionEvent[];
  readonly expectedScene: string;
  readonly expectedState: Readonly<Record<string, unknown>>;
}

const INITIAL_SCENE = ${inline(ctx.document.initialScene)};
const KNOWN_SCENES: readonly string[] = ${literal(ctx.knownScenes)};
/** State pointers written by the rules; compared after every scenario. */
const OBSERVABLE_PATHS: readonly string[] = ${literal(ctx.observablePaths)};
const INITIAL_OBSERVABLE_STATE: Readonly<Record<string, unknown>> = ${literal(initialState)};
/** Every event the rules react to (extracted from the rule triggers). */
const ACTION_VOCABULARY: readonly InteractionEvent[] = ${literal(ctx.actionVocabulary)};
/** Event sequences found by fuzzPlaytestSpec and replayed on the reference model before export. */
const VERIFIED_TRACES: readonly VerifiedTrace[] = ${literal(ctx.verifiedTraces)};

const PROPERTY_SEED = ${ctx.fuzzSettings.seed};
const MAX_EVENTS = ${ctx.fuzzSettings.maxStepsPerRun};
const NUM_RUNS = Math.max(1, Number(process.env.GENUI_CONTRACT_RUNS) || ${ctx.fuzzSettings.numRuns});

interface Observation {
  readonly outcome: OutcomeStatus;
  readonly scene: string;
  readonly state: Record<string, unknown>;
}

async function observe(driver: AppDriver): Promise<Observation> {
  const state: Record<string, unknown> = {};
  for (const pointer of OBSERVABLE_PATHS) {
    state[pointer] = await driver.getState(pointer);
  }
  return {
    outcome: (await driver.getOutcome()).status,
    scene: await driver.getActiveScene(),
    state,
  };
}

async function play(driver: AppDriver, events: readonly InteractionEvent[]): Promise<Observation> {
  await driver.reset();
  for (const event of events) {
    await driver.dispatch(event);
  }
  return observe(driver);
}

const eventSequence = () =>
  fc.array(fc.constantFrom(...ACTION_VOCABULARY), { minLength: 1, maxLength: MAX_EVENTS });

describe(\`\${${inline(ctx.document.brief.title)}} behavioral contract (driver: \${TARGET})\`, () => {
  it("starts in the playing state on the initial scene", async () => {
    const result = await play(createDriver(), []);
    expect(result.outcome).toBe("playing");
    expect(result.scene).toBe(INITIAL_SCENE);
    expect(result.state).toEqual(INITIAL_OBSERVABLE_STATE);
  });

  for (const trace of VERIFIED_TRACES) {
    it(\`reaches "\${trace.outcome}" through the verified \${trace.events.length}-event trace\`, async () => {
      const result = await play(createDriver(), trace.events);
      expect(result.outcome).toBe(trace.outcome);
      expect(result.scene).toBe(trace.expectedScene);
      expect(KNOWN_SCENES).toContain(result.scene);
      expect(result.state).toEqual(trace.expectedState);
    });
  }

  it("reset() restores the initial state after a full session", async () => {
    const driver = createDriver();
    const longest = VERIFIED_TRACES.reduce<readonly InteractionEvent[]>(
      (acc, trace) => (trace.events.length > acc.length ? trace.events : acc),
      ACTION_VOCABULARY.slice(0, MAX_EVENTS),
    );
    await play(driver, longest);
    await driver.reset();
    const result = await observe(driver);
    expect(result.outcome).toBe("playing");
    expect(result.scene).toBe(INITIAL_SCENE);
    expect(result.state).toEqual(INITIAL_OBSERVABLE_STATE);
  });

  it.skipIf(ACTION_VOCABULARY.length === 0)(
    "matches the reference model on random event sequences",
    async () => {
      const driver = createDriver();
      await fc.assert(
        fc.asyncProperty(eventSequence(), async (events) => {
          const expected = await play(createReferenceDriver(), events);
          const actual = await play(driver, events);
          expect(actual).toEqual(expected);
        }),
        { numRuns: NUM_RUNS, seed: PROPERTY_SEED },
      );
    },
  );

  it.skipIf(ACTION_VOCABULARY.length === 0)(
    "replays the same sequence identically after reset()",
    async () => {
      const driver = createDriver();
      await fc.assert(
        fc.asyncProperty(eventSequence(), async (events) => {
          const first = await play(driver, events);
          const second = await play(driver, events);
          expect(second).toEqual(first);
        }),
        { numRuns: NUM_RUNS, seed: PROPERTY_SEED + 1 },
      );
    },
  );
});
`;
}
