import type { SkillPackContext } from "./skill-pack-types.js";

/**
 * Generators for the TypeScript files under `contracts/` in an exported Skill Pack.
 *
 * Every dynamic value (brief text, element keys, rule data) is embedded through
 * `literal()` / `inline()`. Both escape U+2028/U+2029 (which end `//` comments) and
 * `*\/` (which ends block comments), so untrusted strings can never leave their
 * string literal or comment in the generated source.
 */

function codeSafe(jsonText: string): string {
  return jsonText
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029")
    .replace(/\*\//g, "*\\/");
}

/** Pretty-printed JSON literal, safe to embed as a TypeScript expression. */
function literal(value: unknown): string {
  return codeSafe(JSON.stringify(value, null, 2) ?? "undefined");
}

/** Single-line JSON literal, safe inside expressions and comments. */
export function inline(value: unknown): string {
  return codeSafe(JSON.stringify(value) ?? "undefined");
}

const GENERATED_HEADER = (title: string) =>
  `// Generated by GenUI Studio for ${inline(title)}. Do not edit: re-export the Skill Pack to change behavior.`;

export function buildAppDriverTs(): string {
  return `/**
 * Shared contract between the behavioral tests and any implementation of the app.
 *
 * - contracts/reference-driver.ts drives the bundled reference model and passes.
 * - contracts/production-driver.ts must drive your real app. It throws
 *   NotImplementedError until you wire it.
 */
import type { InteractionEvent, OutcomeStatus } from "@genui-studio/core";

export type { InteractionEvent, OutcomeStatus };

export class NotImplementedError extends Error {
  constructor(method: string) {
    super(
      \`[GenUI Contract] Production AppDriver.\${method}() is not implemented yet. \` +
        "Wire contracts/production-driver.ts to your built application and re-run invariants.pbt.test.ts.",
    );
    this.name = "NotImplementedError";
  }
}

export interface AppOutcome {
  readonly status: OutcomeStatus;
  readonly reason: string;
}

type MaybePromise<T> = T | Promise<T>;

export interface AppDriver {
  /** Return the app to its initial state (initial scene, outcome "playing"). */
  reset(): MaybePromise<void>;
  /** Perform one user or timer interaction and wait until the app has settled. */
  dispatch(event: InteractionEvent): MaybePromise<void>;
  /** Read app state by RFC 6901 JSON Pointer, e.g. "/score". */
  getState(pointer: string): MaybePromise<unknown>;
  /** Current outcome: "playing", "win", "lose" or "complete". */
  getOutcome(): MaybePromise<AppOutcome>;
  /** Current scene id. */
  getActiveScene(): MaybePromise<string>;
}
`;
}

export function buildReferenceDriverTs(ctx: SkillPackContext): string {
  return `${GENERATED_HEADER(ctx.document.brief.title)}
//
// Reference model: runs contracts/wireframe.spec.json through the GenUI interaction
// rule engine. It defines the expected behavior; your app must match it.
import {
  createInteractionRuleEngine,
  type InteractionRule,
  type InteractionRuleEngine,
} from "@genui-studio/core";
import type { AppDriver } from "./app-driver";
import behavioralSpecJson from "./wireframe.spec.json";

interface BehavioralSpec {
  readonly initialScene: string;
  readonly spec: { readonly state?: Record<string, unknown> };
  readonly rules: readonly InteractionRule[];
}

const behavioralSpec = behavioralSpecJson as unknown as BehavioralSpec;

function createEngine(): InteractionRuleEngine {
  return createInteractionRuleEngine({
    initialState: structuredClone(behavioralSpec.spec.state ?? {}),
    rules: behavioralSpec.rules,
    initialScene: behavioralSpec.initialScene,
  });
}

export function createReferenceDriver(): AppDriver {
  let engine = createEngine();
  return {
    reset() {
      engine = createEngine();
    },
    dispatch(event) {
      engine.dispatch(event);
    },
    getState(pointer) {
      return engine.store.get(pointer);
    },
    getOutcome() {
      return engine.getOutcome();
    },
    getActiveScene() {
      return engine.getActiveScene();
    },
  };
}
`;
}

