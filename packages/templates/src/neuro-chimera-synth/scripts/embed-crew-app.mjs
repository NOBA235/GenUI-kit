// Embeds every file of the Kiro Crew app into lib/chimera/crew-app-files.ts.
// The lab's "Download Kiro Crew App bundle" button zips these files, and the shared template
// bundler skips .py files, so the module is also how the Python hooks reach exported projects.
// Run after editing anything under kiro-crew-app/:
//   node packages/templates/src/neuro-chimera-synth/scripts/embed-crew-app.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const templateDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const appDir = path.join(templateDir, "kiro-crew-app");
const SKIPPED_DIRS = new Set(["node_modules", "dist", ".git"]);
/** Code-point order, so the output does not depend on the machine's locale. */
const byCodePoint = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function walk(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => byCodePoint(a.name, b.name))) {
    if (SKIPPED_DIRS.has(entry.name)) continue;
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(abs));
    else if (entry.isFile()) out.push(path.relative(appDir, abs).split(path.sep).join("/"));
  }
  return out;
}

const files = walk(appDir).sort(byCodePoint);
const entries = files.map((rel) => {
  const content = fs.readFileSync(path.join(appDir, rel), "utf8").replace(/\r\n/g, "\n");
  return `  { path: ${JSON.stringify(rel)}, content: ${JSON.stringify(content)} },`;
});

const out = `// Generated by scripts/embed-crew-app.mjs. Do not edit; edit kiro-crew-app/ and re-run the script.
export interface CrewTextFile {
  readonly path: string;
  readonly content: string;
}

/** Every file of the Kiro Crew app, relative to the app root, sorted, with LF line endings. */
export const CREW_APP_FILES: readonly CrewTextFile[] = [
${entries.join("\n")}
];
`;

fs.writeFileSync(path.join(templateDir, "lib", "chimera", "crew-app-files.ts"), out);
console.log(`Embedded ${files.length} Kiro Crew app files`);
