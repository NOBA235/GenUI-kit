// Embeds the Kiro Crew app's Python files into lib/chimera/crew-python-files.ts.
// The shared template bundler only copies known text extensions and skips .py, so the
// template ships these files through this module instead. Run after editing backend/*.py:
//   node packages/templates/src/neuro-chimera-synth/scripts/embed-crew-python.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const templateDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const appDir = path.join(templateDir, "kiro-crew-app");
const files = ["backend/__init__.py", "backend/hooks.py"];

const entries = files.map((rel) => {
  const content = fs.readFileSync(path.join(appDir, rel), "utf8").replace(/\r\n/g, "\n");
  return `  { path: ${JSON.stringify(`kiro-crew-app/${rel}`)}, content: ${JSON.stringify(content)} },`;
});

const out = `// Generated by scripts/embed-crew-python.mjs. Do not edit; edit kiro-crew-app/backend/*.py instead.
export interface CrewTextFile {
  readonly path: string;
  readonly content: string;
}

/** Python files of the Kiro Crew app (the template bundler does not copy .py files). */
export const CREW_PYTHON_FILES: readonly CrewTextFile[] = [
${entries.join("\n")}
];
`;

fs.writeFileSync(path.join(templateDir, "lib", "chimera", "crew-python-files.ts"), out);
console.log(`Embedded ${files.length} Python files`);
