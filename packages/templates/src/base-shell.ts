const EXCLUDED_EXPORT_SEGMENTS = new Set([
  "node_modules",
  ".next",
  ".git",
  ".turbo",
]);

function isExcludedExportPath(relPath: string): boolean {
  const normalized = relPath.replace(/\\/g, "/");
  const segments = normalized.split("/");
  if (segments.some((s) => EXCLUDED_EXPORT_SEGMENTS.has(s))) {
    return true;
  }
  const base = segments[segments.length - 1] ?? "";
  return base === ".env" || (base.startsWith(".env.") && base !== ".env.example");
}

export interface MergedShellOptions {
  readonly projectName?: string;
}

/**
 * Merges `base-nextjs-shell` with a Mode A (Internal Native) or Mode B (Ingested Standalone)
 * template into a complete, runnable Next.js 15 project file map.
 */
export function mergeTemplateWithNextjsShell(
  entry: DualModeTemplateEntry,
  options: MergedShellOptions = {},
): Record<string, string> {
  const { manifest, sourceFiles, themeCss, skillMd, kiroPowerMd, steeringMd } =
    entry;
  const projectName = options.projectName ?? `${manifest.slug}-website`;

  // Mode B (Standalone Ingested): return the exact clean standalone source tree
  // augmented with GenUI catalog bridge, SKILL.md, POWER.md, and PBT suite.
  if (manifest.mode === "standalone") {
    const out: Record<string, string> = {};
    for (const file of sourceFiles) {
      if (isExcludedExportPath(file.path)) continue;
      if (file.kind === "source") {
        out[file.path] = file.content;
      } else {
        out[`genui/${file.path}`] = file.content;
      }
    }

    if (!out["package.json"]) {
      out["package.json"] = BASE_NEXTJS_SHELL_FILES["package.json"]!;
    }

    out["genui/manifest.json"] = JSON.stringify(manifest, null, 2);
    out["genui/theme.css"] = themeCss;
    out["SKILL.md"] = skillMd;
    out[`.claude/skills/${manifest.slug}/SKILL.md`] = skillMd;
    out[`.kiro/powers/${manifest.slug}/POWER.md`] = kiroPowerMd;
    out[`.kiro/steering/${manifest.slug}-steering.md`] = steeringMd;
    const assetDoc = sourceFiles.find((f) => f.path === "ASSET_MANIFEST.md");
    out["ASSET_MANIFEST.md"] =
      assetDoc?.content ??
      `# ${manifest.title} — Asset Manifest\n\nAll procedural meshes, styles, and catalog blocks for \`${manifest.slug}\`.\n`;
    return out;
  }

  // Mode A (Internal Native): merge base-nextjs-shell with the template's files
  const shellPkg = JSON.parse(BASE_NEXTJS_SHELL_FILES["package.json"]!) as {
    name: string;
    version: string;
    private: boolean;
    type: string;
    scripts: Record<string, string>;
    dependencies: Record<string, string>;
    devDependencies: Record<string, string>;
  };

  const mergedFiles: Record<string, string> = {
    ...BASE_NEXTJS_SHELL_FILES,
    "package.json": JSON.stringify(
      {
        ...shellPkg,
        name: projectName,
        version: manifest.version,
        dependencies: {
          ...shellPkg.dependencies,
          ...manifest.dependencies,
        },
        devDependencies: {
          ...shellPkg.devDependencies,
          ...manifest.devDependencies,
        },
      },
      null,
      2,
    ),
    "app/template-theme.css": themeCss,
    "app/layout.tsx": `import React from "react";
import "./globals.css";

export const metadata = {
  title: ${JSON.stringify(manifest.title)},
  description: ${JSON.stringify(manifest.description)},
};

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <html lang="en">
      <body data-template-theme=${JSON.stringify(manifest.slug)}>{children}</body>
    </html>
  );
}
`,
    "app/page.tsx": `"use client";
import React, { useMemo } from "react";
import { JSONUIProvider } from "@json-render/react";
import {
  createTelemetryTracker,
  createTimeTravelStateStore,
  SafeGenUIRenderer,
  wrapRegistryWithTelemetry,
} from "@genui-studio/core";
import { verifiedCatalog, initialPageSpecs } from "../src/template/catalog";
import { templateComponents } from "../src/template/components";

export default function ${toPascalCase(manifest.slug)}Page() {
  const store = useMemo(() => createTimeTravelStateStore({}), []);
  const tracker = useMemo(() => createTelemetryTracker(), []);
  const safeRegistry = useMemo(
    () =>
      wrapRegistryWithTelemetry(verifiedCatalog, templateComponents, {
        telemetryTracker: tracker,
      }),
    [tracker],
  );
  const spec = initialPageSpecs["home"] ?? Object.values(initialPageSpecs)[0] ?? null;

  return (
    <main data-template-theme=${JSON.stringify(manifest.slug)} className="min-h-screen">
      <JSONUIProvider registry={safeRegistry} store={store}>
        <SafeGenUIRenderer
          spec={spec}
          registry={safeRegistry}
          catalog={verifiedCatalog}
          telemetryTracker={tracker}
        />
      </JSONUIProvider>
    </main>
  );
}
`,
  };

  for (const file of sourceFiles) {
    if (isExcludedExportPath(file.path)) continue;
    mergedFiles[`src/template/${file.path}`] = file.content;
  }

  mergedFiles["src/template/manifest.json"] = JSON.stringify(manifest, null, 2);
  mergedFiles["SKILL.md"] = skillMd;
  mergedFiles[`.claude/skills/${manifest.slug}/SKILL.md`] = skillMd;
  mergedFiles[`.kiro/powers/${manifest.slug}/POWER.md`] = kiroPowerMd;
  mergedFiles[`.kiro/steering/${manifest.slug}-steering.md`] = steeringMd;
  const assetManifestFile = sourceFiles.find(
    (f) => f.path === "ASSET_MANIFEST.md",
  );
  mergedFiles["ASSET_MANIFEST.md"] =
    assetManifestFile?.content ??
    `# ${manifest.title} — Asset Manifest\n\nExported from GenUI Studio Dual-Mode Registry.\n`;
  mergedFiles["__tests__/invariants.fuzz.test.ts"] =
    buildTemplateFuzzTest(manifest.slug);
  mergedFiles["README.md"] = `# ${manifest.title}

${manifest.description}

Exported from **GenUI Studio** (Mode: \`${manifest.mode}\`, Slug: \`${manifest.slug}\`).

## Quickstart
\`\`\`bash
pnpm install
pnpm dev
\`\`\`
`;

  return mergedFiles;
}

function toPascalCase(slug: string): string {
  return slug
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join("");
}

function buildTemplateFuzzTest(slug: string): string {
  return `import { describe, expect, it } from "vitest";
import { runCatalogInvariantSuite } from "@genui-studio/core/testing";
import { verifiedCatalog } from "../src/template/catalog";

describe("${slug} GenUI Invariant Suite", () => {
  it("satisfies INV-PBT-01 through INV-PBT-04", () => {
    const report = runCatalogInvariantSuite(verifiedCatalog, { numRuns: 25 });
    expect(report.allPassed).toBe(true);
  });
});
`;
}

export function mapFilesRecordToSourceFiles(
  record: Readonly<Record<string, string>>,
  kind: TemplateSourceFile["kind"] = "source",
): TemplateSourceFile[] {
  return Object.entries(record).map(([filePath, content]) => ({
    path: filePath,
    content,
    kind,
  }));
}
